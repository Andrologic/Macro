import {readFile, writeFile, readdir} from 'node:fs/promises';
import {resolve, dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
import {build} from 'esbuild';
import {standalone} from './generate-transfer-transit.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const directory = resolve(root, 'contracts/macro-pilot/v2/transfer-authority');
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
const dependencyPaths = [
  '../strict-json.mjs', '../strict-json.d.mts',
  '../transfer-decision.schema.json', '../transfer-decision-schema-set.json',
  '../transfer-decision.d.ts', '../transfer-decision-validate.mjs',
  '../transfer-decision-validate.d.mts', '../transfer-decision.md',
  '../transfer-transit/decision-browser.generated.mjs',
  '../transfer-transit/decision-browser.generated.d.mts', '../transfer-transit/NOTICE.txt',
  '../../../../dev/generate-transfer-transit.mjs',
];
async function resources(paths) {
  return Promise.all([...paths].sort().map(async path => ({path, sha256:hash(await readFile(resolve(directory,path)))})));
}
export async function generateAuthority() {
  const schemaBytes = await readFile(resolve(directory,'schema.json'));
  const schema = JSON.parse(schemaBytes);
  const decision = JSON.parse(await readFile(resolve(directory,'../transfer-decision.schema.json'),'utf8'));
  const generated = await standalone(schema,['message'],[decision]);
  const built = await build({stdin:{contents:`${generated.source}\n${generated.cleanup}\n${generated.empty}`,resolveDir:directory,loader:'js'},bundle:true,write:false,platform:'browser',format:'esm',target:'es2022',minify:true,legalComments:'none'});
  const name = key => 'Authority' + key[0].toUpperCase() + key.slice(1);
  const render = s => {
    if(s.$ref) {const [base,key] = s.$ref.split('#/$defs/'); return base ? `DecisionDefinitions[${JSON.stringify(key)}]` : name(key);}
    if('const' in s) return JSON.stringify(s.const);
    if(s.enum) return s.enum.map(x=>JSON.stringify(x)).join(' | ');
    if(s.oneOf || s.allOf) return '(' + (s.oneOf ?? s.allOf).map(render).join(s.oneOf?' | ':' & ') + ')';
    if(s.type==='object') return '{' + Object.entries(s.properties).map(([key,value])=>JSON.stringify(key)+(s.required?.includes(key)?'':'?')+': '+render(value)).join('; ') + '}';
    if(['string','boolean','null'].includes(s.type)) return s.type;
    throw Error('Review authority type rendering');
  };
  const dependencies = await resources(dependencyPaths);
  return {
    'shape.generated.mjs':'// Generated by dev/generate-transfer-authority.mjs. See NOTICE.txt. Do not edit.\n'+built.outputFiles[0].text,
    'types.generated.d.mts':"// Generated by dev/generate-transfer-authority.mjs. Do not edit.\nimport type {DecisionDefinitions} from '../transfer-decision.js';\n"+Object.entries(schema.$defs).map(([key,value])=>`export type ${name(key)} = ${render(value)};`).join('\n')+'\n',
    'identities.generated.mjs':'// Generated dependency identities. No support or authentication claim.\nexport const IDENTITIES=Object.freeze('+JSON.stringify({schema_sha256:hash(schemaBytes),dependencies,dependency_set_sha256:hash(JSON.stringify(dependencies))})+');\n',
  };
}
export async function generateManifest() {
  const normative=['NOTICE.txt','contract.md','schema.json','validate.mjs','validate.d.mts','shape.generated.mjs','shape.generated.d.mts','types.generated.d.mts','identities.generated.mjs','identities.generated.d.mts'];
  const names=(await readdir(directory)).filter(name=>name!=='transfer-authority-contract.json').sort();
  if(JSON.stringify(names)!==JSON.stringify([...normative].sort()))throw Error('Review authority normative resources');
  return JSON.stringify({format:'transfer-authority-1',status:'contract_only_no_runtime_authority',resources:await resources([...normative,...dependencyPaths,'../../../../dev/generate-transfer-authority.mjs'])},null,2)+'\n';
}
if(process.argv[1]===fileURLToPath(import.meta.url)) {
  for(const [name,source] of Object.entries(await generateAuthority())) {
    const path=resolve(directory,name);
    if(process.argv.includes('--check')) {if(await readFile(path,'utf8')!==source)throw Error('Stale authority artifact: '+name);}
    else await writeFile(path,source);
  }
  const path=resolve(directory,'transfer-authority-contract.json'),source=await generateManifest();
  if(process.argv.includes('--check')) {if(await readFile(path,'utf8')!==source)throw Error('Stale authority manifest');}
  else await writeFile(path,source);
}
