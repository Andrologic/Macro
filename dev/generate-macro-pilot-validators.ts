import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';
import Ajv2020 from 'ajv/dist/2020.js';
import addFormats from 'ajv-formats';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { build } from 'esbuild';

const schemaPaths = [
  'contracts/macro-pilot/v1/common.schema.json',
  'contracts/macro-pilot/v1/identity.schema.json',
  'contracts/macro-pilot/v1/supervision.schema.json',
  'contracts/macro-pilot/v1/protocol.schema.json',
  'contracts/macro-pilot/v1/schema.json',
  'contracts/macro-pilot/transport/schema.json',
] as const;

type JsonSchema = { $id: string } & Record<string, unknown>;

export const macroPilotSchemaPaths = (projectRoot: string): string[] =>
  schemaPaths.map((path) => resolve(projectRoot, path));

export async function generateMacroPilotValidators(projectRoot: string): Promise<string> {
  const schemas = await Promise.all(
    macroPilotSchemaPaths(projectRoot).map(async (path) =>
      JSON.parse(await readFile(path, 'utf8')) as JsonSchema
    )
  );
  const root = schemas.at(-2)!;
  const transport = schemas.at(-1)!;
  const ajv = new Ajv2020({
    strict: false,
    inlineRefs: false,
    allErrors: false,
    messages: false,
    code: { source: true, esm: true, optimize: 2 },
  });
  addFormats(ajv, { formats: ['date-time', 'uri'] });
  for (const schema of schemas) ajv.addSchema(schema);

  const generated = standaloneCode(ajv, {
    schemaValidate: root.$id,
    resultValidate: `${transport.$id}#/$defs/deliveryResult`,
    deliveryValidate: `${transport.$id}#/$defs/delivery`,
  });
  // Every generated function can retain errors, including referenced schemas.
  const slots = [...new Set([...generated.matchAll(/\b([A-Za-z_$][\w$]*)\.errors\s*=/g)].map(match => match[1]))];
  if (!slots.length || slots.some(name => !/^validate\d+$/.test(name))) throw new Error('Review A1 diagnostic slots.');
  const cleanup = `
export function clearErrors(){${slots.map(name => `${name}.errors=null;`).join('')}}
export function diagnosticsEmpty(){return ${slots.map(name => `${name}.errors==null`).join('&&')}}
export const diagnosticSlots=${slots.length};`;
  const bundled = await build({
    stdin: {
      contents: generated + cleanup,
      resolveDir: projectRoot,
      sourcefile: 'macro-pilot-schema-validators.generated.js',
      loader: 'js',
    },
    bundle: true,
    write: false,
    format: 'esm',
    platform: 'browser',
    target: 'esnext',
    legalComments: 'none',
    minify: true,
  });

  const output = bundled.outputFiles[0];
  if (!output) throw new Error('esbuild did not produce Macro Pilot validators.');
  return '// Generated by dev/generate-macro-pilot-validators.ts. See schemaValidators.notice.txt. Do not edit.\n' + `// Diagnostic slots: ${slots.length}.\n` + output.text;
}


const artifactDirectory = 'src/services/macroPilot';
export async function generateMacroPilotIdentity(projectRoot: string, generated: string): Promise<string> {
  const paths = [...schemaPaths, 'bun.lock', 'dev/generate-macro-pilot-validators.ts',
    'copilot-bridge/src/entry.ts', 'copilot-bridge/src/connect-codec.ts',
    'copilot-bridge/src/connect-codec-operations.ts', 'copilot-bridge/src/connect-codec-values.ts', 'copilot-bridge/src/connect-codec-framing.ts',
    'src/services/macroPilot/protocol.ts', 'src/services/macroPilot/schemaValidators.ts',
    'src/services/macroPilot/schemaValidators.generated.d.mts', 'src/services/macroPilot/schemaValidators.notice.txt'];
  const resources = await Promise.all(paths.sort().map(async path => ({ path,
    sha256: createHash('sha256').update(await readFile(resolve(projectRoot, path))).digest('hex') })));
  resources.push({ path: `${artifactDirectory}/schemaValidators.generated.mjs`, sha256: createHash('sha256').update(generated).digest('hex') });
  resources.sort((a, b) => a.path.localeCompare(b.path, 'en'));
  let schemaNodes = 0, schemaStringUnits = 0;
  const visit = (value: unknown): void => {
    schemaNodes++;
    if (typeof value === 'string') schemaStringUnits += value.length;
    else if (Array.isArray(value)) value.forEach(visit);
    else if (value && typeof value === 'object') for (const [key, child] of Object.entries(value)) { schemaStringUnits += key.length; visit(child); }
  };
  for (const path of macroPilotSchemaPaths(projectRoot)) visit(JSON.parse(await readFile(path, 'utf8')));
  const diagnosticSlots = Number(generated.match(/^\/\/ Diagnostic slots: (\d+)/m)?.[1]);
  if (!Number.isSafeInteger(diagnosticSlots) || diagnosticSlots < 1) throw new Error('Missing A1 diagnostics inventory');
  // Logical persistent module inventory. Engine bytecode/JIT/VM and allocator
  // overhead are not physical bounds inferred from these source descriptors.
  const inventory = { source_utf16_units: generated.length, schema_nodes: schemaNodes,
    schema_string_units: schemaStringUnits, diagnostic_slots: diagnosticSlots,
    logical_units: 2 * generated.length + 256 * schemaNodes + 2 * schemaStringUnits + 256 * diagnosticSlots + 32768 };
  const retained_units = Math.ceil(inventory.logical_units / 262144) * 262144;
  return JSON.stringify({ format: 'macro-pilot-a1-private-1', retained_units, inventory, resources }, null, 2) + '\n';
}

if (import.meta.main) {
  const projectRoot = resolve(fileURLToPath(new URL('..', import.meta.url)));
  const generated = await generateMacroPilotValidators(projectRoot);
  const identity = await generateMacroPilotIdentity(projectRoot, generated);
  for (const [name, source] of [['schemaValidators.generated.mjs', generated], ['schemaValidators.identity.json', identity]]) {
    const path = resolve(projectRoot, artifactDirectory, name);
    if (process.argv.includes('--check')) {
      if (await readFile(path, 'utf8') !== source) throw new Error(`Stale Macro Pilot validator: ${name}`);
    } else await writeFile(path, source);
  }
}
