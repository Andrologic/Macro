import { afterEach, beforeEach, expect, it, mock } from 'bun:test';
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import en from '../../../i18n/locales/en.json';
const save = mock(async () => '/synthetic/new-profile.json' as string | null);
const open = mock(async () => '/synthetic/old-profile.json' as string | null);
const schedule = mock(async (..._args: unknown[]) => {});
const success = mock(() => {});
mock.module('react-i18next', () => ({ useTranslation: () => ({ t: (key: string) => key.split('.').reduce((v: any, k) => v?.[k], en) ?? key }) }));
mock.module('../../../services/tauriDialog', () => ({ open, save }));
mock.module('../../../services/tauriIpc', () => ({ isTauriAvailable: () => true, localBackupStatus: async () => ({ browser: null }), localBackupSchedule: schedule }));
mock.module('../../../services/localBackup', () => ({ captureBackupBrowserState: () => ({ macro_chat_queued_submissions_v1: '[]' }) }));
mock.module('../../ui/toastService', () => ({ notify: { success } }));
const { BackupSettingsSection } = await import('./BackupSettingsSection');
let root: Root;
let container: HTMLDivElement;
const button = (text: string) => [...document.querySelectorAll('button')].find(b => b.textContent === text)!;
beforeEach(async () => {
  save.mockClear(); open.mockClear(); schedule.mockClear(); success.mockClear();
  container = document.createElement('div'); document.body.append(container); root = createRoot(container);
  await act(async () => root.render(<BackupSettingsSection />));
});
afterEach(async () => { await act(async () => root.unmount()); container.remove(); });
it('cancels the native selector without preparing an operation', async () => {
  save.mockImplementationOnce(async () => null);
  await act(async () => button(en.backup.export).click());
  expect(document.querySelector('[role="dialog"]')).toBeNull();
  expect(schedule).not.toHaveBeenCalled();
});
it('confirms the chosen destination and captures browser recovery state only on confirmation', async () => {
  const trigger = button(en.backup.export); trigger.focus();
  await act(async () => trigger.click());
  expect(save).toHaveBeenCalledTimes(1);
  expect(document.activeElement).toBe(button(en.common.cancel));
  expect(document.querySelector('input')?.value).toBe('/synthetic/new-profile.json');
  expect(schedule).not.toHaveBeenCalled();
  await act(async () => button(en.backup.confirm).click());
  expect(schedule).toHaveBeenCalledWith('export', '/synthetic/new-profile.json', { macro_chat_queued_submissions_v1: '[]' }, true);
  expect(document.querySelector('[role="dialog"]')).toBeNull();
  expect(container.textContent).toContain(en.backup.scheduled);
  expect(button(en.backup.restore).disabled).toBe(true);
});
it('explains replacement, traps focus and closes on Escape without restoring', async () => {
  const trigger = button(en.backup.restore); trigger.focus();
  await act(async () => trigger.click());
  expect(open).toHaveBeenCalledTimes(1);
  expect(document.querySelector('[role="dialog"]')?.textContent).toContain(en.backup.confirmRestore);
  button(en.backup.confirmReplace).focus();
  await act(async () => document.dispatchEvent(new KeyboardEvent('keydown', { key: 'Tab', bubbles: true })));
  expect(document.activeElement).toBe(document.querySelector('input'));
  await act(async () => document.dispatchEvent(new KeyboardEvent('keydown', { key: 'Escape', bubbles: true })));
  expect(document.querySelector('[role="dialog"]')).toBeNull();
  expect(document.activeElement).toBe(trigger);
  expect(schedule).not.toHaveBeenCalled();
});
it('keeps the selected archive and shows failure inside the confirmation for retry', async () => {
  schedule.mockImplementationOnce(async () => { throw new Error('Synthetic incompatible archive'); });
  await act(async () => button(en.backup.restore).click());
  await act(async () => button(en.backup.confirmReplace).click());
  const dialog = document.querySelector('[role="dialog"]');
  expect(dialog?.textContent).toContain('Synthetic incompatible archive');
  expect(dialog?.querySelector('input')?.value).toBe('/synthetic/old-profile.json');
  expect(success).not.toHaveBeenCalled();
  expect(button(en.backup.confirmReplace).disabled).toBe(false);
});
it('keeps confirmation locked until native preparation settles', async () => {
  let finish!: () => void;
  schedule.mockImplementationOnce(() => new Promise<void>(resolve => { finish = resolve; }));
  await act(async () => button(en.backup.restore).click());
  await act(async () => button(en.backup.confirmReplace).click());
  expect(button(en.common.cancel).disabled).toBe(true);
  expect(button(en.backup.confirmReplace).disabled).toBe(true);
  expect(document.querySelector('input')?.disabled).toBe(true);
  await act(async () => document.dispatchEvent(new KeyboardEvent('keydown', { key: 'Escape', bubbles: true })));
  expect(document.querySelector('[role="dialog"]')).not.toBeNull();
  await act(async () => finish());
  expect(document.querySelector('[role="dialog"]')).toBeNull();
  expect(schedule).toHaveBeenCalledTimes(1);
});
