import { afterEach, expect, it, mock } from "bun:test";
import { act } from "react";
import { createRoot, type Root } from "react-dom/client";
import type { NativeModelCatalogue } from "../types/generated/ipc";
let calls = 0;
let catalogue: NativeModelCatalogue = { revision: "empty", models: [], unavailableProviders: [] };
let wait: Promise<void> | undefined;
mock.module("../services/tauriIpc", () => ({ executionModelChoices: async () => { calls++; if (wait) await wait; return catalogue; } }));
mock.module("../components/agsdl/useAgsdlTranslation", () => ({ useAgsdlTranslation: () => ({ t: (key: string) => key }) }));
const { useAgsdlModelCatalogue: store } = await import("./useAgsdlModelCatalogue");
const { MacroAgentConfiguration } = await import("../components/agsdl/MacroAgentConfiguration");
const { macroAgentConfiguration } = await import("../services/agsdl/macroAgentConfiguration");
const { macroNativeModelEdition } = await import("../services/agsdl/nativeModelEdition");
const { createLegacyExample } = await import("../services/agsdl/examples");
const { projectViewer } = await import("../services/agsdl/viewer");
let root: Root | undefined;
let host: HTMLDivElement;
afterEach(() => { act(() => root?.unmount()); host?.remove(); });
it("coalesces native requests and refreshes an empty catalogue after a manual model was added", async () => {
  let release!: () => void;
  wait = new Promise(resolve => { release = resolve; });
  const first = store.getState().load(true); const second = store.getState().load(true);
  expect(calls).toBe(1); release(); await Promise.all([first, second]); wait = undefined;
  const source = createLegacyExample("release");
  const configuration = macroAgentConfiguration(source, projectViewer(source).graphs[0].cards[0]);
  host = document.createElement("div"); document.body.appendChild(host); root = createRoot(host);
  const render = (key: string) => root!.render(<MacroAgentConfiguration key={key} configuration={configuration} providerId="" modelId="" disabled={false} onChange={() => {}} />);
  await act(async () => render('first'));
  expect(host.textContent).not.toContain('Native model');
  const openingCalls = calls;
  catalogue = { revision: 'added', unavailableProviders: [], models: [{ providerId: 'manual', modelId: 'configured', providerName: 'Native provider', modelName: 'Native model', edition: macroNativeModelEdition('manual', 'configured') }] };
  await act(async () => render('reopened'));
  expect(calls).toBe(openingCalls + 1);
  expect(host.textContent).toContain('Native provider');
  const provider = host.querySelector<HTMLSelectElement>('select')!;
  await act(async () => { provider.value = 'manual'; provider.dispatchEvent(new Event('change', { bubbles: true })); });
  expect(store.getState().catalogue?.models[0].modelId).toBe('configured');
});
